function defaultStyle(kind: SceneObject['kind'], funcIdx = 0): SceneStyle {
  return {
    color:
      kind === 'point'
        ? DEFAULT_POINT_COLOR
        : kind === 'function'
        ? DEFAULT_FUNC_COLORS[funcIdx % DEFAULT_FUNC_COLORS.length]
        : kind === 'integral'
        ? '#0d9488'
        : DEFAULT_STROKE_COLOR,
    dashed: false,
    lineWidth: kind === 'function' ? 2.4 : 2,
    showLabel: kind === 'point',
    pointSize: 4,
  };
}

// Tách đối số cấp cao nhất tôn trọng ngoặc đơn (...)
function splitTopLevelArgs(inside: string): string[] {
  const args: string[] = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < inside.length; i++) {
    const ch = inside[i];
    if (ch === '(' || ch === '[') depth++;
    else if (ch === ')' || ch === ']') depth = Math.max(0, depth - 1);
    else if (ch === ',' && depth === 0) {
      args.push(inside.slice(start, i).trim());
      start = i + 1;
    }
  }
  const tail = inside.slice(start).trim();
  if (tail) args.push(tail);
  return args;
}

// Chuyển biểu thức toán GeoGebra thành hàm JS an toàn
function compileMathExpression(rawExpr: string, vars: Record<string, number> = {}): ((x: number) => number) | null {
  let expr = rawExpr
    .replace(/²/g, '^2')
    .replace(/³/g, '^3')
    .replace(/π/g, 'pi')
    .replace(/\s+/g, '');

  if (!expr) return null;

  // Thêm dấu * cho nhân ngầm định: 2x -> 2*x, 2(x+1) -> 2*(x+1), x(x+1) -> x*(x+1), (x)(y) -> (x)*(y)
  expr = expr
    .replace(/(\d)([a-zA-Z(])/g, '$1*$2')
    .replace(/(\))(\d|[a-zA-Z(])/g, '$1*$2')
    .replace(/([x])(\()/g, '$1*$2');

  // Kiểm tra whitelist ký tự cơ bản
  if (/[^a-zA-Z0-9_+\-*/^().,]/.test(expr)) {
    return null;
  }

  // Đổi ^ thành **
  const jsExpr = expr.replace(/\^/g, '**');

  try {
    const scopeKeys = Object.keys(vars);
    const scopeVals = scopeKeys.map((k) => vars[k]);
    const fn = new Function(
      'x',
      ...scopeKeys,
      `const {sin,cos,tan,abs,sqrt,exp,pow,floor,ceil,round,min,max,PI:pi,E:e} = Math;
       const ln = Math.log;
       const log = Math.log10;
       const cot = (v) => 1 / Math.tan(v);
       const sec = (v) => 1 / Math.cos(v);
       const csc = (v) => 1 / Math.sin(v);
       const arcsin = Math.asin;
       const arccos = Math.acos;
       const arctan = Math.atan;
       try { return Number(${jsExpr}); } catch { return NaN; }`
    );
    // Test 1 lần
    const testVal = fn(1, ...scopeVals);
    if (typeof testVal !== 'number') return null;
    return (x: number) => fn(x, ...scopeVals);
  } catch {
    return null;
  }
}

function evalScalar(raw: string, numericVars: Record<string, number>): number | null {
  const fn = compileMathExpression(raw, numericVars);
  if (!fn) return null;
  const val = fn(0);
  return Number.isFinite(val) ? val : null;
}

// Chiếu 3D -> 2D kiểu tủ (cavalier oblique projection) chuẩn SGK Toán Việt Nam
function project3DTo2D(x: number, y: number, z: number): Point2D {
  return {
    x: y - 0.38 * x,
    y: z - 0.26 * x,
  };
}

function parseColor(args: string[]): string | null {
  if (args.length === 1) {
    const clean = args[0].replace(/["']/g, '').trim().toLowerCase();
    return NAMED_COLORS[clean] || (clean.startsWith('#') ? clean : null);
  }
  if (args.length >= 3) {
    const r = Math.max(0, Math.min(255, Math.round(Number(args[0]))));
    const g = Math.max(0, Math.min(255, Math.round(Number(args[1]))));
    const b = Math.max(0, Math.min(255, Math.round(Number(args[2]))));
    if ([r, g, b].every(Number.isFinite)) {
      return `rgb(${r}, ${g}, ${b})`;
    }
  }
  return null;
}

function evaluateGeoGebraScript(commandsText: string): {
  objects: Map<string, SceneObject>;
  order: string[];
  warningCount: number;
} {
  const objects = new Map<string, SceneObject>();
  const order: string[] = [];
  const numericVars: Record<string, number> = {};
  let warningCount = 0;
  let autoIdx = 1;
  let funcCount = 0;

  const nextAutoName = (prefix: string) => `${prefix}_${autoIdx++}`;

  const registerObj = (obj: SceneObject) => {
    if (!objects.has(obj.name)) {
      order.push(obj.name);
    }
    objects.set(obj.name, obj);
    return obj;
  };

  const getLineLike = (obj: SceneObject): { p1: Point2D; p2: Point2D } | null => {
    if (obj.kind === 'segment' || obj.kind === 'line' || obj.kind === 'vector') {
      return { p1: obj.p1, p2: obj.p2 };
    }
    return null;
  };

  const resolveExpr = (rawInput: string, assignedName?: string): SceneObject | null => {
    const input = rawInput.trim();
    if (!input) return null;

    // 1. Tham chiếu tên đối tượng có sẵn
    if (objects.has(input)) {
      return objects.get(input)!;
    }

    // 2. Tọa độ điểm (x, y) hoặc (x, y, z)
    if (input.startsWith('(') && input.endsWith(')')) {
      const coords = splitTopLevelArgs(input.slice(1, -1));
      if (coords.length === 2 || coords.length === 3) {
        const nums = coords.map((c) => evalScalar(c, numericVars));
        if (nums.every((n) => n !== null)) {
          const pt =
            nums.length === 3
              ? project3DTo2D(nums[0]!, nums[1]!, nums[2]!)
              : { x: nums[0]!, y: nums[1]! };
          const name = assignedName || nextAutoName('Pt');
          return registerObj({
            kind: 'point',
            name,
            x: pt.x,
            y: pt.y,
            style: defaultStyle('point'),
            autoGenerated: !assignedName,
          });
        }
      }
    }

    // 3. Lệnh hàm FunctionCall(arg1, arg2, ...)
    const callMatch = input.match(/^([A-Za-z]+)\((.*)\)$/);
    if (!callMatch) return null;

    const fnName = callMatch[1];
    const fnLower = fnName.toLowerCase();
    const args = splitTopLevelArgs(callMatch[2]);

    if (fnLower === 'segment' && args.length >= 2) {
      const p1 = resolveExpr(args[0]);
      const p2 = resolveExpr(args[1]);
      if (p1?.kind === 'point' && p2?.kind === 'point') {
        const name = assignedName || nextAutoName('seg');
        return registerObj({
          kind: 'segment',
          name,
          p1: { x: p1.x, y: p1.y },
          p2: { x: p2.x, y: p2.y },
          style: defaultStyle('segment'),
        });
      }
    }

    if ((fnLower === 'line' || fnLower === 'ray') && args.length >= 2) {
      const o1 = resolveExpr(args[0]);
      const o2 = resolveExpr(args[1]);
      if (o1?.kind === 'point' && o2?.kind === 'point') {
        const name = assignedName || nextAutoName(fnLower === 'ray' ? 'ray' : 'line');
        return registerObj({
          kind: 'line',
          name,
          p1: { x: o1.x, y: o1.y },
          p2: { x: o2.x, y: o2.y },
          rayOnly: fnLower === 'ray',
          style: defaultStyle('line'),
        });
      }
      if (o1?.kind === 'point' && o2) {
        const l = getLineLike(o2);
        if (l) {
          const dx = l.p2.x - l.p1.x;
          const dy = l.p2.y - l.p1.y;
          const name = assignedName || nextAutoName('line');
          return registerObj({
            kind: 'line',
            name,
            p1: { x: o1.x, y: o1.y },
            p2: { x: o1.x + dx, y: o1.y + dy },
            style: defaultStyle('line'),
          });
        }
      }
    }

    if (fnLower === 'vector' && args.length >= 2) {
      const p1 = resolveExpr(args[0]);
      const p2 = resolveExpr(args[1]);
      if (p1?.kind === 'point' && p2?.kind === 'point') {
        const name = assignedName || nextAutoName('vec');
        return registerObj({
          kind: 'vector',
          name,
          p1: { x: p1.x, y: p1.y },
          p2: { x: p2.x, y: p2.y },
          style: defaultStyle('vector'),
        });
      }
    }

    if (fnLower === 'midpoint') {
      if (args.length === 2) {
        const p1 = resolveExpr(args[0]);
        const p2 = resolveExpr(args[1]);
        if (p1?.kind === 'point' && p2?.kind === 'point') {
          const name = assignedName || nextAutoName('M');
          return registerObj({
            kind: 'point',
            name,
            x: (p1.x + p2.x) / 2,
            y: (p1.y + p2.y) / 2,
            style: defaultStyle('point'),
            autoGenerated: !assignedName,
          });
        }
      } else if (args.length === 1) {
        const o = resolveExpr(args[0]);
        const l = o ? getLineLike(o) : null;
        if (l) {
          const name = assignedName || nextAutoName('M');
          return registerObj({
            kind: 'point',
            name,
            x: (l.p1.x + l.p2.x) / 2,
            y: (l.p1.y + l.p2.y) / 2,
            style: defaultStyle('point'),
            autoGenerated: !assignedName,
          });
        }
      }
    }

    if ((fnLower === 'perpendicularline' || fnLower === 'parallelline') && args.length >= 2) {
      const p = resolveExpr(args[0]);
      const lineObj = resolveExpr(args[1]);
      const l = lineObj ? getLineLike(lineObj) : null;
      if (p?.kind === 'point' && l) {
        const dx = l.p2.x - l.p1.x;
        const dy = l.p2.y - l.p1.y;
        const vx = fnLower === 'perpendicularline' ? -dy : dx;
        const vy = fnLower === 'perpendicularline' ? dx : dy;
        const name = assignedName || nextAutoName('line');
        return registerObj({
          kind: 'line',
          name,
          p1: { x: p.x, y: p.y },
          p2: { x: p.x + vx, y: p.y + vy },
          style: defaultStyle('line'),
        });
      }
    }

    if (fnLower === 'intersect' && args.length >= 2) {
      const o1 = resolveExpr(args[0]);
      const o2 = resolveExpr(args[1]);
      const l1 = o1 ? getLineLike(o1) : null;
      const l2 = o2 ? getLineLike(o2) : null;
      if (l1 && l2) {
        const x1 = l1.p1.x, y1 = l1.p1.y, x2 = l1.p2.x, y2 = l1.p2.y;
        const x3 = l2.p1.x, y3 = l2.p1.y, x4 = l2.p2.x, y4 = l2.p2.y;
        const denom = (x1 - x2) * (y3 - y4) - (y1 - y2) * (x3 - x4);
        if (Math.abs(denom) > 1e-8) {
          const px = ((x1 * y2 - y1 * x2) * (x3 - x4) - (x1 - x2) * (x3 * y4 - y3 * x4)) / denom;
          const py = ((x1 * y2 - y1 * x2) * (y3 - y4) - (y1 - y2) * (x3 * y4 - y3 * x4)) / denom;
          const name = assignedName || nextAutoName('I');
          return registerObj({
            kind: 'point',
            name,
            x: px,
            y: py,
            style: defaultStyle('point'),
            autoGenerated: !assignedName,
          });
        }
      }
      // Line + Circle
      const lineSide = l1 || l2;
      const circleSide = o1?.kind === 'circle' ? o1 : o2?.kind === 'circle' ? o2 : null;
      if (lineSide && circleSide) {
        const dx = lineSide.p2.x - lineSide.p1.x;
        const dy = lineSide.p2.y - lineSide.p1.y;
        const len2 = dx * dx + dy * dy;
        if (len2 > 1e-9) {
          const fx = lineSide.p1.x - circleSide.cx;
          const fy = lineSide.p1.y - circleSide.cy;
          const b = 2 * (fx * dx + fy * dy);
          const c = fx * fx + fy * fy - circleSide.r * circleSide.r;
          const disc = b * b - 4 * len2 * c;
          if (disc >= 0) {
            const t = (-b + Math.sqrt(disc)) / (2 * len2);
            const name = assignedName || nextAutoName('I');
            return registerObj({
              kind: 'point',
              name,
              x: lineSide.p1.x + t * dx,
              y: lineSide.p1.y + t * dy,
              style: defaultStyle('point'),
              autoGenerated: !assignedName,
            });
          }
        }
      }
    }

    if (fnLower === 'polygon' && args.length >= 3) {
      const pts: Point2D[] = [];
      for (const a of args) {
        const pt = resolveExpr(a);
        if (pt?.kind === 'point') pts.push({ x: pt.x, y: pt.y });
      }
      if (pts.length >= 3) {
        const name = assignedName || nextAutoName('poly');
        return registerObj({
          kind: 'polygon',
          name,
          vertices: pts,
          style: defaultStyle('polygon'),
        });
      }
    }

    if (fnLower === 'circle') {
      if (args.length === 2) {
        const center = resolveExpr(args[0]);
        const rNum = evalScalar(args[1], numericVars);
        if (center?.kind === 'point' && rNum !== null && rNum > 0) {
          const name = assignedName || nextAutoName('c');
          return registerObj({
            kind: 'circle',
            name,
            cx: center.x,
            cy: center.y,
            r: rNum,
            style: defaultStyle('circle'),
          });
        }
        const ptOnCircle = resolveExpr(args[1]);
        if (center?.kind === 'point' && ptOnCircle?.kind === 'point') {
          const r = Math.hypot(ptOnCircle.x - center.x, ptOnCircle.y - center.y);
          const name = assignedName || nextAutoName('c');
          return registerObj({
            kind: 'circle',
            name,
            cx: center.x,
            cy: center.y,
            r,
            style: defaultStyle('circle'),
          });
        }
      } else if (args.length === 3) {
        const pA = resolveExpr(args[0]);
        const pB = resolveExpr(args[1]);
        const pC = resolveExpr(args[2]);
        if (pA?.kind === 'point' && pB?.kind === 'point' && pC?.kind === 'point') {
          const D = 2 * (pA.x * (pB.y - pC.y) + pB.x * (pC.y - pA.y) + pC.x * (pA.y - pB.y));
          if (Math.abs(D) > 1e-8) {
            const a2 = pA.x * pA.x + pA.y * pA.y;
            const b2 = pB.x * pB.x + pB.y * pB.y;
            const c2 = pC.x * pC.x + pC.y * pC.y;
            const ux = (a2 * (pB.y - pC.y) + b2 * (pC.y - pA.y) + c2 * (pA.y - pB.y)) / D;
            const uy = (a2 * (pC.x - pB.x) + b2 * (pA.x - pC.x) + c2 * (pB.x - pA.x)) / D;
            const r = Math.hypot(pA.x - ux, pA.y - uy);
            const name = assignedName || nextAutoName('c');
            return registerObj({
              kind: 'circle',
              name,
              cx: ux,
              cy: uy,
              r,
              style: defaultStyle('circle'),
            });
          }
        }
      }
    }

    if (fnLower === 'semicircle' && args.length >= 2) {
      const p1 = resolveExpr(args[0]);
      const p2 = resolveExpr(args[1]);
      if (p1?.kind === 'point' && p2?.kind === 'point') {
        const cx = (p1.x + p2.x) / 2;
        const cy = (p1.y + p2.y) / 2;
        const r = Math.hypot(p2.x - p1.x, p2.y - p1.y) / 2;
        const semiAngleStart = Math.atan2(p1.y - cy, p1.x - cx);
        const name = assignedName || nextAutoName('semi');
        return registerObj({
          kind: 'circle',
          name,
          cx,
          cy,
          r,
          semiAngleStart,
          style: defaultStyle('circle'),
        });
      }
    }

    if (fnLower === 'angle' && args.length >= 3) {
      const pA = resolveExpr(args[0]);
      const pB = resolveExpr(args[1]);
      const pC = resolveExpr(args[2]);
      if (pA?.kind === 'point' && pB?.kind === 'point' && pC?.kind === 'point') {
        const name = assignedName || nextAutoName('ang');
        return registerObj({
          kind: 'angle',
          name,
          a: { x: pA.x, y: pA.y },
          b: { x: pB.x, y: pB.y },
          c: { x: pC.x, y: pC.y },
          style: { ...defaultStyle('angle'), color: '#dc2626' },
        });
      }
    }

    if (fnLower === 'integral' && args.length >= 3) {
      const fnObj = objects.get(args[0]);
      const from = evalScalar(args[1], numericVars);
      const to = evalScalar(args[2], numericVars);
      if (fnObj?.kind === 'function' && from !== null && to !== null) {
        const name = assignedName || nextAutoName('area');
        return registerObj({
          kind: 'integral',
          name,
          fn1: fnObj.fn,
          from: Math.min(from, to),
          to: Math.max(from, to),
          style: defaultStyle('integral'),
        });
      }
    }

    if (fnLower === 'integralbetween' && args.length >= 4) {
      const fnObj1 = objects.get(args[0]);
      const fnObj2 = objects.get(args[1]);
      const from = evalScalar(args[2], numericVars);
      const to = evalScalar(args[3], numericVars);
      if (fnObj1?.kind === 'function' && fnObj2?.kind === 'function' && from !== null && to !== null) {
        const name = assignedName || nextAutoName('area');
        return registerObj({
          kind: 'integral',
          name,
          fn1: fnObj1.fn,
          fn2: fnObj2.fn,
          from: Math.min(from, to),
          to: Math.max(from, to),
          style: defaultStyle('integral'),
        });
      }
    }

    return null;
  };

  const lines = commandsText.split('\n');
  for (const rawLine of lines) {
    const cmd = normalizeGeoGebraCommand(rawLine);
    if (!cmd) continue;

    // Style commands
    const styleCall = cmd.match(/^([A-Za-z]+)\((.*)\)$/);
    if (styleCall) {
      const fn = styleCall[1].toLowerCase();
      const args = splitTopLevelArgs(styleCall[2]);
      const targetName = args[0];
      const targetObj = targetName ? objects.get(targetName) : undefined;

      if (fn === 'setlinestyle' && targetObj && args[1] !== undefined) {
        const st = Number(args[1]);
        targetObj.style.dashed = st > 0;
        continue;
      }
      if (fn === 'setlinethickness' && targetObj && args[1] !== undefined) {
        const lw = Number(args[1]);
        if (Number.isFinite(lw) && lw > 0) {
          targetObj.style.lineWidth = Math.max(1, Math.min(6, lw * 0.55));
        }
        continue;
      }
      if (fn === 'setcolor' && targetObj) {
        const parsedColor = parseColor(args.slice(1));
        if (parsedColor) targetObj.style.color = parsedColor;
        continue;
      }
      if (fn === 'showlabel' && targetObj && args[1] !== undefined) {
        targetObj.style.showLabel = args[1].toLowerCase() === 'true';
        continue;
      }
      if (fn === 'setpointsize' && targetObj && args[1] !== undefined) {
        const sz = Number(args[1]);
        if (Number.isFinite(sz)) targetObj.style.pointSize = Math.max(2, Math.min(8, sz));
        continue;
      }
    }

    // Function definition: f(x) = ... or y = ...
    const funcMatch = cmd.match(/^([A-Za-z][A-Za-z0-9_]*)\(\s*x\s*\)\s*=\s*(.+)$/);
    if (funcMatch) {
      const fn = compileMathExpression(funcMatch[2], numericVars);
      if (fn) {
        registerObj({
          kind: 'function',
          name: funcMatch[1],
          expr: funcMatch[2],
          fn,
          style: defaultStyle('function', funcCount++),
        });
      } else {
        warningCount++;
      }
      continue;
    }

    if (/^y\s*=\s*(.+)$/i.test(cmd)) {
      const rhs = cmd.replace(/^y\s*=\s*/i, '');
      const fn = compileMathExpression(rhs, numericVars);
      if (fn) {
        registerObj({
          kind: 'function',
          name: nextAutoName('f'),
          expr: rhs,
          fn,
          style: defaultStyle('function', funcCount++),
        });
      } else {
        warningCount++;
      }
      continue;
    }

    // Vertical line x = a
    const xLineMatch = cmd.match(/^x\s*=\s*(.+)$/i);
    if (xLineMatch) {
      const xVal = evalScalar(xLineMatch[1], numericVars);
      if (xVal !== null) {
        registerObj({
          kind: 'line',
          name: nextAutoName('xline'),
          p1: { x: xVal, y: -1 },
          p2: { x: xVal, y: 1 },
          style: defaultStyle('line'),
        });
      } else {
        warningCount++;
      }
      continue;
    }

    // Assignment: Name = Expr
    const assignMatch = cmd.match(/^([A-Za-z][A-Za-z0-9_']*)\s*=\s*(.+)$/);
    if (assignMatch) {
      const [, varName, rhs] = assignMatch;
      const obj = resolveExpr(rhs, varName);
      if (!obj) {
        const scalarVal = evalScalar(rhs, numericVars);
        if (scalarVal !== null) {
          numericVars[varName] = scalarVal;
        } else {
          warningCount++;
        }
      }
      continue;
    }

    // Standalone construction
    const obj = resolveExpr(cmd);
    if (!obj) {
      warningCount++;
    }
  }

  return { objects, order, warningCount };
}

export const LocalGeometryBoard = forwardRef<LocalGeometryBoardRef, LocalGeometryBoardProps>(
  ({ commandsText, appMode, showAxes, showGrid, onStatusChange }, ref) => {
    const canvasRef = useRef<HTMLCanvasElement>(null);
    const wrapperRef = useRef<HTMLDivElement>(null);

    const parsed = useMemo(() => evaluateGeoGebraScript(commandsText), [commandsText]);

    // Viewport state: pixelsPerUnit (scale) and world center (cx, cy)
    const [viewport, setViewport] = useState<{ cx: number; cy: number; scale: number }>({
      cx: 1.5,
      cy: 1.5,
      scale: 52,
    });
    const [labelOffsets, setLabelOffsets] = useState<Record<string, Point2D>>({});
    const dragRef = useRef<{
      mode: 'pan' | 'label';
      targetName?: string;
      startClientX: number;
      startClientY: number;
      startCx: number;
      startCy: number;
      startLabelOffset?: Point2D;
    } | null>(null);

    const computeAutoViewport = useCallback(
      (width: number, height: number) => {
        const xs: number[] = [];
        const ys: number[] = [];

        parsed.order.forEach((name) => {
          const obj = parsed.objects.get(name);
          if (!obj) return;
          if (obj.kind === 'point') {
            xs.push(obj.x);
            ys.push(obj.y);
          } else if (obj.kind === 'segment' || obj.kind === 'vector') {
            xs.push(obj.p1.x, obj.p2.x);
            ys.push(obj.p1.y, obj.p2.y);
          } else if (obj.kind === 'polygon') {
            obj.vertices.forEach((v) => {
              xs.push(v.x);
              ys.push(v.y);
            });
          } else if (obj.kind === 'circle') {
            xs.push(obj.cx - obj.r, obj.cx + obj.r);
            ys.push(obj.cy - obj.r, obj.cy + obj.r);
          }
        });

        if (xs.length === 0 || ys.length === 0) {
          return {
            cx: 0,
            cy: 0,
            scale: appMode === 'graphing' ? 46 : 55,
          };
        }

        const minX = Math.min(...xs);
        const maxX = Math.max(...xs);
        const minY = Math.min(...ys);
        const maxY = Math.max(...ys);

        const spanX = Math.max(2, maxX - minX);
        const spanY = Math.max(2, maxY - minY);
        const usableW = Math.max(240, width - 130);
        const usableH = Math.max(200, height - 110);
        const scale = Math.max(16, Math.min(130, Math.min(usableW / spanX, usableH / spanY)));

        return {
          cx: (minX + maxX) / 2,
          cy: (minY + maxY) / 2,
          scale,
        };
      },
      [parsed, appMode]
    );

    const autoFitView = useCallback(() => {
      const w = wrapperRef.current?.clientWidth || 1000;
      const h = 520;
      setViewport(computeAutoViewport(w, h));
    }, [computeAutoViewport]);

    useEffect(() => {
      onStatusChange?.({ objectCount: parsed.order.length, warningCount: parsed.warningCount });
      if (parsed.order.length > 0) {
        autoFitView();
      }
      // eslint-disable-next-line react-hooks/exhaustive-deps
    }, [commandsText]);

    const drawScene = useCallback(
      (ctx: CanvasRenderingContext2D, width: number, height: number) => {
        ctx.save();
        ctx.fillStyle = '#ffffff';
        ctx.fillRect(0, 0, width, height);

        const toScreen = (wx: number, wy: number): Point2D => ({
          x: width / 2 + (wx - viewport.cx) * viewport.scale,
          y: height / 2 - (wy - viewport.cy) * viewport.scale,
        });

        const toWorld = (sx: number, sy: number): Point2D => ({
          x: viewport.cx + (sx - width / 2) / viewport.scale,
          y: viewport.cy - (sy - height / 2) / viewport.scale,
        });

        const worldTopLeft = toWorld(0, 0);
        const worldBottomRight = toWorld(width, height);
        const xMin = Math.min(worldTopLeft.x, worldBottomRight.x);
        const xMax = Math.max(worldTopLeft.x, worldBottomRight.x);
        const yMin = Math.min(worldTopLeft.y, worldBottomRight.y);
        const yMax = Math.max(worldTopLeft.y, worldBottomRight.y);

        // 1. Grid
        if (showGrid) {
          const step = viewport.scale < 25 ? 2 : 1;
          ctx.strokeStyle = '#e2e8f0';
          ctx.lineWidth = 1;
          ctx.beginPath();
          for (let gx = Math.floor(xMin / step) * step; gx <= Math.ceil(xMax); gx += step) {
            const p = toScreen(gx, 0);
            ctx.moveTo(p.x, 0);
            ctx.lineTo(p.x, height);
          }
          for (let gy = Math.floor(yMin / step) * step; gy <= Math.ceil(yMax); gy += step) {
            const p = toScreen(0, gy);
            ctx.moveTo(0, p.y);
            ctx.lineTo(width, p.y);
          }
          ctx.stroke();
        }

        // 2. Axes
        if (showAxes) {
          const origin = toScreen(0, 0);
          ctx.strokeStyle = '#334155';
          ctx.lineWidth = 1.4;
          ctx.beginPath();
          // Ox
          ctx.moveTo(0, origin.y);
          ctx.lineTo(width - 8, origin.y);
          // Oy
          ctx.moveTo(origin.x, height);
          ctx.lineTo(origin.x, 8);
          ctx.stroke();

          // Arrows
          ctx.fillStyle = '#334155';
          ctx.beginPath();
          ctx.moveTo(width - 2, origin.y);
          ctx.lineTo(width - 11, origin.y - 4);
          ctx.lineTo(width - 11, origin.y + 4);
          ctx.closePath();
          ctx.fill();

          ctx.beginPath();
          ctx.moveTo(origin.x, 2);
          ctx.lineTo(origin.x - 4, 11);
          ctx.lineTo(origin.x + 4, 11);
          ctx.closePath();
          ctx.fill();

          ctx.font = 'italic bold 13px "Be Vietnam Pro", sans-serif';
          ctx.fillStyle = '#0f172a';
          ctx.fillText('x', width - 16, origin.y - 8);
          ctx.fillText('y', origin.x + 10, 16);
          ctx.font = '11px "Be Vietnam Pro", sans-serif';
          ctx.fillStyle = '#475569';
          const tickStep = viewport.scale < 25 ? 2 : 1;
          for (let tx = Math.floor(xMin / tickStep) * tickStep; tx <= Math.ceil(xMax); tx += tickStep) {
            if (tx === 0) continue;
            const pt = toScreen(tx, 0);
            if (pt.x > 16 && pt.x < width - 22) {
              ctx.beginPath();
              ctx.moveTo(pt.x, origin.y - 3);
              ctx.lineTo(pt.x, origin.y + 3);
              ctx.stroke();
              ctx.fillText(String(tx), pt.x - 4, origin.y + 15);
            }
          }
          for (let ty = Math.floor(yMin / tickStep) * tickStep; ty <= Math.ceil(yMax); ty += tickStep) {
            if (ty === 0) continue;
            const pt = toScreen(0, ty);
            if (pt.y > 22 && pt.y < height - 14) {
              ctx.beginPath();
              ctx.moveTo(origin.x - 3, pt.y);
              ctx.lineTo(origin.x + 3, pt.y);
              ctx.stroke();
              ctx.fillText(String(ty), origin.x + 7, pt.y + 4);
            }
          }
          ctx.fillText('O', origin.x - 14, origin.y + 14);
        }

        // 3. Integrals (shaded areas drawn under curves & lines)
        parsed.order.forEach((name) => {
          const obj = parsed.objects.get(name);
          if (!obj || obj.kind !== 'integral') return;
          const samples = 140;
          const dx = (obj.to - obj.from) / samples;
          if (dx <= 0) return;

          ctx.save();
          ctx.fillStyle = 'rgba(13, 148, 136, 0.22)';
          ctx.beginPath();
          for (let i = 0; i <= samples; i++) {
            const x = obj.from + i * dx;
            const y = obj.fn1(x);
            const sp = toScreen(x, Number.isFinite(y) ? y : 0);
            if (i === 0) ctx.moveTo(sp.x, sp.y);
            else ctx.lineTo(sp.x, sp.y);
          }
          for (let i = samples; i >= 0; i--) {
            const x = obj.from + i * dx;
            const y = obj.fn2 ? obj.fn2(x) : 0;
            const sp = toScreen(x, Number.isFinite(y) ? y : 0);
            ctx.lineTo(sp.x, sp.y);
          }
          ctx.closePath();
          ctx.fill();
          ctx.restore();
        });

        // 4. Polygons, lines, segments, circles, functions, angles
        parsed.order.forEach((name) => {
          const obj = parsed.objects.get(name);
          if (!obj || obj.kind === 'point' || obj.kind === 'integral') return;

          ctx.save();
          ctx.strokeStyle = obj.style.color;
          ctx.lineWidth = obj.style.lineWidth;
          ctx.setLineDash(obj.style.dashed ? [6, 5] : []);

          if (obj.kind === 'polygon' && obj.vertices.length >= 3) {
            ctx.beginPath();
            obj.vertices.forEach((v, idx) => {
              const s = toScreen(v.x, v.y);
              if (idx === 0) ctx.moveTo(s.x, s.y);
              else ctx.lineTo(s.x, s.y);
            });
            ctx.closePath();
            ctx.fillStyle = 'rgba(15, 118, 110, 0.05)';
            ctx.fill();
            ctx.stroke();
          } else if (obj.kind === 'segment') {
            const s1 = toScreen(obj.p1.x, obj.p1.y);
            const s2 = toScreen(obj.p2.x, obj.p2.y);
            ctx.beginPath();
            ctx.moveTo(s1.x, s1.y);
            ctx.lineTo(s2.x, s2.y);
            ctx.stroke();
          } else if (obj.kind === 'vector') {
            const s1 = toScreen(obj.p1.x, obj.p1.y);
            const s2 = toScreen(obj.p2.x, obj.p2.y);
            ctx.beginPath();
            ctx.moveTo(s1.x, s1.y);
            ctx.lineTo(s2.x, s2.y);
            ctx.stroke();
            const ang = Math.atan2(s2.y - s1.y, s2.x - s1.x);
            ctx.setLineDash([]);
            ctx.fillStyle = obj.style.color;
            ctx.beginPath();
            ctx.moveTo(s2.x, s2.y);
            ctx.lineTo(s2.x - 10 * Math.cos(ang - 0.35), s2.y - 10 * Math.sin(ang - 0.35));
            ctx.lineTo(s2.x - 10 * Math.cos(ang + 0.35), s2.y - 10 * Math.sin(ang + 0.35));
            ctx.closePath();
            ctx.fill();
          } else if (obj.kind === 'line') {
            const dx = obj.p2.x - obj.p1.x;
            const dy = obj.p2.y - obj.p1.y;
            const len = Math.hypot(dx, dy);
            if (len > 1e-8) {
              const ext = 250;
              const startPt = obj.rayOnly
                ? obj.p1
                : { x: obj.p1.x - (dx / len) * ext, y: obj.p1.y - (dy / len) * ext };
              const endPt = { x: obj.p1.x + (dx / len) * ext, y: obj.p1.y + (dy / len) * ext };
              const s1 = toScreen(startPt.x, startPt.y);
              const s2 = toScreen(endPt.x, endPt.y);
              ctx.beginPath();
              ctx.moveTo(s1.x, s1.y);
              ctx.lineTo(s2.x, s2.y);
              ctx.stroke();
            }
          } else if (obj.kind === 'circle') {
            const c = toScreen(obj.cx, obj.cy);
            const sr = obj.r * viewport.scale;
            ctx.beginPath();
            if (typeof obj.semiAngleStart === 'number') {
              ctx.arc(c.x, c.y, sr, -obj.semiAngleStart - Math.PI, -obj.semiAngleStart, false);
            } else {
              ctx.arc(c.x, c.y, sr, 0, Math.PI * 2);
            }
            ctx.stroke();
          } else if (obj.kind === 'angle') {
            const sb = toScreen(obj.b.x, obj.b.y);
            const sa = toScreen(obj.a.x, obj.a.y);
            const sc = toScreen(obj.c.x, obj.c.y);
            const v1x = sa.x - sb.x, v1y = sa.y - sb.y;
            const v2x = sc.x - sb.x, v2y = sc.y - sb.y;
            const l1 = Math.hypot(v1x, v1y), l2 = Math.hypot(v2x, v2y);
            if (l1 > 1 && l2 > 1) {
              const u1x = v1x / l1, u1y = v1y / l1;
              const u2x = v2x / l2, u2y = v2y / l2;
              const dot = u1x * u2x + u1y * u2y;
              ctx.setLineDash([]);
              if (Math.abs(dot) < 0.04) {
                const sq = 13;
                ctx.beginPath();
                ctx.moveTo(sb.x + u1x * sq, sb.y + u1y * sq);
                ctx.lineTo(sb.x + (u1x + u2x) * sq, sb.y + (u1y + u2y) * sq);
                ctx.lineTo(sb.x + u2x * sq, sb.y + u2y * sq);
                ctx.stroke();
              } else {
                const a1 = Math.atan2(u1y, u1x);
                const a2 = Math.atan2(u2y, u2x);
                let diff = a2 - a1;
                while (diff > Math.PI) diff -= 2 * Math.PI;
                while (diff < -Math.PI) diff += 2 * Math.PI;
                ctx.beginPath();
                ctx.arc(sb.x, sb.y, 18, a1, a1 + diff, diff < 0);
                ctx.stroke();
              }
            }
          } else if (obj.kind === 'function') {
            ctx.beginPath();
            let started = false;
            let prevSy = 0;
            const stepPx = 2;
            for (let sx = 0; sx <= width; sx += stepPx) {
              const wx = toWorld(sx, 0).x;
              const wy = obj.fn(wx);
              if (!Number.isFinite(wy) || Math.abs(wy) > 200) {
                started = false;
                continue;
              }
              const sy = toScreen(wx, wy).y;
              if (!started || Math.abs(sy - prevSy) > height * 0.65) {
                ctx.moveTo(sx, sy);
                started = true;
              } else {
                ctx.lineTo(sx, sy);
              }
              prevSy = sy;
            }
            ctx.stroke();
          }

          ctx.restore();
        });

        // 5. Points & Labels (drawn last on top)
        parsed.order.forEach((name) => {
          const obj = parsed.objects.get(name);
          if (!obj || obj.kind !== 'point') return;
          const sp = toScreen(obj.x, obj.y);

          ctx.save();
          ctx.fillStyle = obj.style.color;
          ctx.strokeStyle = '#ffffff';
          ctx.lineWidth = 1.5;
          ctx.beginPath();
          ctx.arc(sp.x, sp.y, obj.style.pointSize, 0, Math.PI * 2);
          ctx.fill();
          ctx.stroke();

          if (obj.style.showLabel && !obj.autoGenerated) {
            const offset = labelOffsets[obj.name] || { x: 7, y: -7 };
            const cleanLabel = obj.name.replace(/_prime/g, "'");
            ctx.font = 'bold 13px "Be Vietnam Pro", sans-serif';
            const lx = sp.x + offset.x;
            const ly = sp.y + offset.y;
            ctx.strokeStyle = 'rgba(255,255,255,0.92)';
            ctx.lineWidth = 3.5;
            ctx.strokeText(cleanLabel, lx, ly);
            ctx.fillStyle = '#0f172a';
            ctx.fillText(cleanLabel, lx, ly);
          }
          ctx.restore();
        });

        ctx.restore();
      },
      [parsed, viewport, showAxes, showGrid, labelOffsets]
    );

    const [containerWidth, setContainerWidth] = useState<number>(1000);

    useEffect(() => {
      const wrapper = wrapperRef.current;
      if (!wrapper) return;
      const syncSize = () => {
        if (wrapper.clientWidth > 0) {
          setContainerWidth(wrapper.clientWidth);
        }
      };
      syncSize();
      if (typeof ResizeObserver !== 'undefined') {
        const ro = new ResizeObserver(syncSize);
        ro.observe(wrapper);
        return () => ro.disconnect();
      }
      window.addEventListener('resize', syncSize);
      return () => window.removeEventListener('resize', syncSize);
    }, []);

    useEffect(() => {
      const canvas = canvasRef.current;
      const wrapper = wrapperRef.current;
      if (!canvas || !wrapper) return;

      const width = Math.max(320, wrapper.clientWidth || containerWidth || 1000);
      const height = 520;
      const dpr = Math.max(2, window.devicePixelRatio || 1);

      canvas.width = width * dpr;
      canvas.height = height * dpr;
      canvas.style.width = `${width}px`;
      canvas.style.height = `${height}px`;

      const ctx = canvas.getContext('2d');
      if (!ctx) return;
      ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
      drawScene(ctx, width, height);
    }, [drawScene, containerWidth]);

    useImperativeHandle(ref, () => ({
      toDataURL: () => {
        const canvas = canvasRef.current;
        if (!canvas) {
          throw new Error('Bảng vẽ chưa sẵn sàng để chụp ảnh.');
        }
        return canvas.toDataURL('image/png');
      },
      autoFitView,
    }));

    const handleMouseDown = (e: React.MouseEvent<HTMLCanvasElement>) => {
      const canvas = canvasRef.current;
      if (!canvas) return;
      const rect = canvas.getBoundingClientRect();
      const sx = e.clientX - rect.left;
      const sy = e.clientY - rect.top;

      // Kiểm tra xem có đang bấm gần điểm/nhãn điểm để kéo nhãn hay không
      let nearestName: string | undefined;
      let nearestDist = 26;
      parsed.order.forEach((name) => {
        const obj = parsed.objects.get(name);
        if (!obj || obj.kind !== 'point' || obj.autoGenerated) return;
        const px = rect.width / 2 + (obj.x - viewport.cx) * viewport.scale;
        const py = rect.height / 2 - (obj.y - viewport.cy) * viewport.scale;
        const d = Math.hypot(sx - px, sy - py);
        if (d < nearestDist) {
          nearestDist = d;
          nearestName = name;
        }
      });

      if (nearestName) {
        dragRef.current = {
          mode: 'label',
          targetName: nearestName,
          startClientX: e.clientX,
          startClientY: e.clientY,
          startCx: viewport.cx,
          startCy: viewport.cy,
          startLabelOffset: labelOffsets[nearestName] || { x: 7, y: -7 },
        };
      } else {
        dragRef.current = {
          mode: 'pan',
          startClientX: e.clientX,
          startClientY: e.clientY,
          startCx: viewport.cx,
          startCy: viewport.cy,
        };
      }
    };

    const handleMouseMove = (e: React.MouseEvent<HTMLCanvasElement>) => {
      const drag = dragRef.current;
      if (!drag) return;
      const dx = e.clientX - drag.startClientX;
      const dy = e.clientY - drag.startClientY;

      if (drag.mode === 'label' && drag.targetName && drag.startLabelOffset) {
        setLabelOffsets((prev) => ({
          ...prev,
          [drag.targetName!]: {
            x: Math.max(-45, Math.min(45, drag.startLabelOffset!.x + dx)),
            y: Math.max(-45, Math.min(45, drag.startLabelOffset!.y + dy)),
          },
        }));
      } else {
        setViewport((prev) => ({
          ...prev,
          cx: drag.startCx - dx / prev.scale,
          cy: drag.startCy + dy / prev.scale,
        }));
      }
    };

    const handleMouseUp = () => {
      dragRef.current = null;
    };

    const handleWheel = (e: React.WheelEvent<HTMLCanvasElement>) => {
      e.preventDefault();
      const factor = e.deltaY < 0 ? 1.12 : 0.89;
      setViewport((prev) => ({
        ...prev,
        scale: Math.max(12, Math.min(220, prev.scale * factor)),
      }));
    };

    return (
      <div ref={wrapperRef} className="relative w-full h-[520px] bg-white select-none">
        <canvas
          ref={canvasRef}
          onMouseDown={handleMouseDown}
          onMouseMove={handleMouseMove}
          onMouseUp={handleMouseUp}
          onMouseLeave={handleMouseUp}
          onWheel={handleWheel}
          className="w-full h-full block cursor-grab active:cursor-grabbing"
        />

        {parsed.order.length === 0 && (
          <div className="pointer-events-none absolute inset-0 flex items-center justify-center p-6">
            <div className="max-w-md rounded-2xl bg-slate-50/90 border border-slate-200 p-4 text-center space-y-1.5 shadow-xs">
              <div className="text-xs font-extrabold text-slate-800">
                Bảng vẽ nhanh nội bộ sẵn sàng (0ms)
              </div>
              <p className="text-[11px] text-slate-600 leading-relaxed">
                Bấm nút <strong>AI tự dựng hình từ đề bài</strong> ở trên hoặc mở{' '}
                <strong>Mã lệnh GeoGebra</strong> để vẽ hình tức thì không phụ thuộc máy chủ ngoài. Kéo nền để di chuyển, kéo quanh điểm để chỉnh vị trí chữ tên điểm.
              </p>
            </div>
          </div>
        )}

        {/* Corner Zoom & Fit Controls */}
        <div className="absolute bottom-3 right-3 flex items-center gap-1 bg-white/95 border border-slate-200 rounded-xl p-1 shadow-sm">
          <button
            type="button"
            onClick={() => setViewport((p) => ({ ...p, scale: Math.min(220, p.scale * 1.2) }))}
            title="Phóng to"
            className="p-1.5 rounded-lg text-slate-600 hover:bg-slate-100 hover:text-slate-900 cursor-pointer"
          >
            <ZoomIn className="w-3.5 h-3.5" />
          </button>
          <button
            type="button"
            onClick={() => setViewport((p) => ({ ...p, scale: Math.max(12, p.scale / 1.2) }))}
            title="Thu nhỏ"
            className="p-1.5 rounded-lg text-slate-600 hover:bg-slate-100 hover:text-slate-900 cursor-pointer"
          >
            <ZoomOut className="w-3.5 h-3.5" />
          </button>
          <button
            type="button"
            onClick={autoFitView}
            title="Căn vừa khung hình"
            className="p-1.5 rounded-lg text-teal-700 hover:bg-teal-50 cursor-pointer flex items-center space-x-1 text-[11px] font-bold px-2"
          >
            <Maximize2 className="w-3 h-3" />
            <span>Căn vừa</span>
          </button>
        </div>
      </div>
    );
  }
);

