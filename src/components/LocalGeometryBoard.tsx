interface Point2D {
  x: number;
  y: number;
}

interface SceneStyle {
  color: string;
  dashed: boolean;
  lineWidth: number;
  showLabel: boolean;
  pointSize: number;
}

type SceneObject =
  | { kind: 'point'; name: string; x: number; y: number; style: SceneStyle; autoGenerated?: boolean }
  | { kind: 'segment'; name: string; p1: Point2D; p2: Point2D; style: SceneStyle }
  | { kind: 'line'; name: string; p1: Point2D; p2: Point2D; rayOnly?: boolean; style: SceneStyle }
  | { kind: 'vector'; name: string; p1: Point2D; p2: Point2D; style: SceneStyle }
  | { kind: 'polygon'; name: string; vertices: Point2D[]; style: SceneStyle }
  | { kind: 'circle'; name: string; cx: number; cy: number; r: number; semiAngleStart?: number; style: SceneStyle }
  | { kind: 'angle'; name: string; a: Point2D; b: Point2D; c: Point2D; style: SceneStyle }
  | { kind: 'function'; name: string; expr: string; fn: (x: number) => number; style: SceneStyle }
  | {
      kind: 'integral';
      name: string;
      fn1: (x: number) => number;
      fn2?: (x: number) => number;
      from: number;
      to: number;
      style: SceneStyle;
    };

